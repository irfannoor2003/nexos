/* ═══════════════════════════════════════════════════
   NEXOS PREMIUM INTERACTIONS (LENIS + GSAP)
   ═══════════════════════════════════════════════════ */
gsap.registerPlugin(ScrollTrigger);

/* INIT LENIS SMOOTH SCROLL */
const lenis = new Lenis({
  duration: 1.2,
  easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
  smooth: true
});
lenis.on('scroll', ScrollTrigger.update);
gsap.ticker.add((time) => { lenis.raf(time * 1000) });
gsap.ticker.lagSmoothing(0);

/* PAGE LOADER */
(function(){
  var loader=document.getElementById('pageLoader');
  if(!loader)return;
  if(document.readyState==='loading'){
    document.addEventListener('DOMContentLoaded',function(){loader.classList.add('loaded');});
  } else { loader.classList.add('loaded'); }
})();

/* SCROLL PROGRESS & BACK TO TOP */
var scrollProgress=document.getElementById('scrollProgress');
var backToTop=document.getElementById('backToTop');
lenis.on('scroll', function(e){
  var progress = (e.animatedScroll / (e.dimensions.scrollHeight - e.dimensions.height)) * 100;
  if(scrollProgress) scrollProgress.style.width=progress+'%';
  if(backToTop){
    if(e.animatedScroll>400){backToTop.classList.add('visible')}
    else{backToTop.classList.remove('visible')}
  }
});
if(backToTop) {
  backToTop.addEventListener('click', () => lenis.scrollTo(0, {duration: 1.5}));
}

/* CURSOR - Premium cursor with smooth ring */
var cur=document.getElementById('cur'),ring=document.getElementById('cur-ring');
if(cur&&ring&&window.innerWidth>1024){
  var mx=0,my=0,rx=0,ry=0;
  document.addEventListener('mousemove',function(e){mx=e.clientX;my=e.clientY;cur.style.left=mx+'px';cur.style.top=my+'px';});
  (function a(){rx+=(mx-rx)*.08;ry+=(my-ry)*.08;ring.style.left=rx+'px';ring.style.top=ry+'px';requestAnimationFrame(a)})();
  var allInteractive=document.querySelectorAll('a,button,.svc-card,.blog-card,.testi-card,.price-card,.team-card,.val-card,.ind-card,.process-card,.faq-card,.why-card,.stat-box,.mission-card,.tl-content,.tl-card,.port-grid-card');
  allInteractive.forEach(el => {
    el.addEventListener('mouseenter',()=>document.body.classList.add('h-cur'));
    el.addEventListener('mouseleave',()=>document.body.classList.remove('h-cur'));
  });
}

/* NAV SCROLL */
var nav=document.getElementById('nav');
lenis.on('scroll', function(e){
  if(nav) nav.classList.toggle('scrolled', e.animatedScroll > 40);
});

/* MOBILE MENU */
function toggleMob(){
  var mob=document.getElementById('mob-menu');
  var ovl=document.getElementById('mob-overlay');
  var ham=document.getElementById('hamburger');
  var isOpen=mob.classList.contains('open');
  mob.classList.toggle('open');
  if(ovl) ovl.classList.toggle('open');
  ham.classList.toggle('active');
  if(!isOpen){ lenis.stop(); if(ovl) ovl.style.pointerEvents=''; } else { lenis.start(); }
}
function closeMob(){
  document.getElementById('mob-menu').classList.remove('open');
  var ovl=document.getElementById('mob-overlay');
  if(ovl) ovl.classList.remove('open');
  document.getElementById('hamburger').classList.remove('active');
  lenis.start();
}
document.addEventListener('keydown', function(e){
  if(e.key==='Escape') closeMob();
});

/* MIND BLOWING SPLIT TEXT ANIMATIONS (Global) */
function initSplitText() {
  const splitElements = document.querySelectorAll('.sec-h, .hero-h1, [class*="-hero-h1"], .cta-title');
  splitElements.forEach(el => {
    if(el.querySelector('.word-outline, .em, .word-em')) {
      gsap.fromTo(el, {opacity:0, y:50}, {opacity:1, y:0, duration:1.5, ease:'power4.out', scrollTrigger:{trigger:el, start:'top 85%'}});
      return;
    }
    
    const text = new SplitType(el, { types: 'words, chars' });
    gsap.from(text.chars, {
      opacity: 0,
      y: 100,
      rotateX: -90,
      stagger: 0.02,
      duration: 1.2,
      ease: 'back.out(1.5)',
      scrollTrigger: {
        trigger: el,
        start: 'top 85%'
      }
    });
  });
}
document.addEventListener('DOMContentLoaded', initSplitText);

/* REVEAL ON SCROLL - standard elements.
   Uses overwrite:'auto' so it never fights page-specific GSAP tweens on the
   same element (avoids the previous "sticky / choppy" double-animation jitter). */
document.addEventListener('DOMContentLoaded', function(){
  gsap.utils.toArray('.reveal, .reveal-l, .reveal-r').forEach(function(el, idx){
    /* Skip elements already handled by a dedicated page-level GSAP tween so we
       don't double-animate them (the cause of choppy reveals). */
    if(el.closest('.svc-grid,.process-grid,.testi-grid,.port-grid-home,.blog-grid-home')) return;
    var dir=el.classList.contains('reveal-l')?-1:el.classList.contains('reveal-r')?1:0;
    var delay=+(el.dataset.delay)||Math.min((idx%5)*60,300);
    gsap.fromTo(el,
      {opacity:0, y:dir===0?40:0, x:dir?dir*60:0},
      {opacity:1, y:0, x:0, duration:1.2, delay:delay/1000, ease:'power4.out', overwrite:'auto',
       scrollTrigger:{trigger:el, start:'top 85%', once:true, toggleActions:'play none none none'}}
    );
  });
});

/* PARALLAX IMAGES & BOXES */
gsap.utils.toArray('.detail-media, .detail-card, .port-home-img img, .blog-card-img img, .svc-tl-media img').forEach(function(el){
  gsap.to(el, {
    yPercent: 15,
    ease: 'none',
    scrollTrigger: { trigger: el.parentElement, start: 'top bottom', end: 'bottom top', scrub: 1 }
  });
});

/* MAGNETIC BUTTONS */
var magBtns=document.querySelectorAll('.btn-primary,.nav-cta,.btn-white,.btn-ghost,.form-submit');
magBtns.forEach(btn => {
  btn.addEventListener('mousemove', function(e){
    var r=btn.getBoundingClientRect();
    var x=e.clientX-r.left-r.width/2;
    var y=e.clientY-r.top-r.height/2;
    gsap.to(btn, {x: x*0.3, y: y*0.3, duration: 0.5, ease: 'power2.out'});
  });
  btn.addEventListener('mouseleave', function(){
    gsap.to(btn, {x: 0, y: 0, duration: 0.5, ease: 'elastic.out(1, 0.3)'});
  });
});

/* TILT MAGNETISM */
var magnetCards=document.querySelectorAll('.svc-card,.testi-card,.price-card,.blog-card,.port-grid-card');
magnetCards.forEach(card => {
  card.addEventListener('mousemove', function(e){
    var r=card.getBoundingClientRect();
    var x=(e.clientX-r.left)/r.width - 0.5;
    var y=(e.clientY-r.top)/r.height - 0.5;
    gsap.to(card, {
      rotateY: x*15,
      rotateX: -y*15,
      boxShadow: (x*20)+'px '+(y*20)+'px 40px rgba(255,255,255,.05)',
      duration: 0.5,
      ease: 'power2.out',
      transformPerspective: 1000
    });
  });
  card.addEventListener('mouseleave', function(){
    gsap.to(card, {rotateY: 0, rotateX: 0, boxShadow: 'none', duration: 0.8, ease: 'elastic.out(1, 0.3)'});
  });
});

/* COUNTER ANIMATION */
gsap.utils.toArray('.counter').forEach(function(el){
  if(el.dataset.done)return;
  ScrollTrigger.create({
    trigger:el,start:'top 85%',
    onEnter:function(){
      el.dataset.done='1';
      var target=+el.dataset.t;
      gsap.fromTo(el, {innerHTML:0}, {innerHTML:target, duration:2.5, ease:'power4.out', snap:{innerHTML:1}, onUpdate:function(){el.innerHTML=Math.round(el.innerHTML)+'+'}});
    }
  });
});

/* THEME TOGGLE */
(function(){
  var root=document.documentElement;
  var btn=document.getElementById('themeToggle');
  var saved=localStorage.getItem('nexos-theme')||'dark';
  root.setAttribute('data-theme',saved);
  if(btn){
    btn.addEventListener('click',function(){
      var next=root.getAttribute('data-theme')==='dark'?'light':'dark';
      root.setAttribute('data-theme',next);
      localStorage.setItem('nexos-theme',next);
    });
  }
})();

/* ANCHOR LINKS SMOOTH SCROLL */
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
  anchor.addEventListener('click', function(e){
    var target = document.querySelector(this.getAttribute('href'));
    if(target){
      e.preventDefault();
      lenis.scrollTo(target, {offset: -80, duration: 1.4});
    }
  });
});

/* PARALLAX ORBS */
var parallaxEls=document.querySelectorAll('.hero-glow,.hero-glow2,.page-hero-glow,.cta-orb');
